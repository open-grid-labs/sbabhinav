// One-off patch: adds coverWidth/coverHeight to the already-generated
// src/data/projects.ts by probing the existing cover.jpg files on disk.
// Does NOT need the Google Drive originals — build-galleries.js has been
// updated to capture these fields on future regenerations too.
const path = require("path");
const REPO = path.resolve(__dirname, "..");
const sharp = require(path.join(REPO, "node_modules", "sharp"));
const fs = require("fs");

const MANIFEST = path.join(REPO, "src", "data", "projects.ts");
const PUB = path.join(REPO, "public", "projects");

(async () => {
	const src = fs.readFileSync(MANIFEST, "utf8");
	const match = src.match(/export const projects: Project\[\] = (\[[\s\S]*?\]);\r?\n\r?\nexport const categories/);
	if (!match) throw new Error("could not locate projects array in manifest");
	const projects = JSON.parse(match[1]);

	for (const p of projects) {
		const coverPath = path.join(PUB, p.slug, "cover.jpg");
		const meta = await sharp(coverPath).metadata();
		p.coverWidth = meta.width;
		p.coverHeight = meta.height;
	}

	const ts = `// AUTO-GENERATED by build-galleries.js — do not edit by hand.
export type Photo = { thumb: string; full: string; w: number; h: number };
export type Project = {
  slug: string;
  name: string;
  category: string;
  location: string;
  featured: boolean;
  cover: string;
  coverWidth: number;
  coverHeight: number;
  count: number;
  photos: Photo[];
};

export const projects: Project[] = ${JSON.stringify(projects, null, 2)};

export const categories = ["All", ...Array.from(new Set(projects.map((p) => p.category)))];
`;
	fs.writeFileSync(MANIFEST, ts);
	console.log(`Patched coverWidth/coverHeight for ${projects.length} projects.`);
})();
